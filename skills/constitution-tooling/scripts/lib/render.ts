// Renders derived files from the data files. critical-path.md is generated, never hand-edited.
import { findCycle } from "./checks.ts";
import { overlaps } from "./glob.ts";
import type { EpicDoc, Model } from "./model.ts";

type EpicView = { id: string; name: string; kind: string; priority: number; points: number; paths: string[]; patchable: string[]; deps: string[]; doc: EpicDoc };

/** Patchable entries may be written with or without the leading .constitution/; compare them the way TSK-009 does. */
function patchOverlap(a: string, b: string): boolean {
  return overlaps(a.replace(/^\.constitution\//, ""), b.replace(/^\.constitution\//, ""));
}

function openPoints(e: EpicDoc): number {
  return (e.data?.tickets ?? []).filter((t: any) => t.status !== "done" && t.status !== "deferred").reduce((a: number, t: any) => a + (t.effort ?? 0), 0);
}

export function planActive(m: Model): { waves: EpicView[][]; outOfBand: EpicView[]; chain: string[]; chainPoints: number; views: EpicView[] } {
  const completed = new Set(m.epics.filter((e) => !e.active).map((e) => e.data?.id));
  const views: EpicView[] = m.epics.filter((e) => e.active && e.data?.id).map((e, i) => ({
    id: e.data.id, name: e.data.name, kind: e.data.kind, priority: e.data.priority ?? i + 1, points: openPoints(e),
    paths: e.data.scope?.paths ?? [], patchable: e.data.scope?.tech_spec_patchable ?? [],
    deps: (e.data.depends_on ?? []).filter((d: string) => !completed.has(d)), doc: e,
  })).sort((a, b) => a.priority - b.priority || a.id.localeCompare(b.id));
  const inBand = views.filter((v) => v.kind !== "out_of_band");
  const outOfBand = views.filter((v) => v.kind === "out_of_band");
  const graph = new Map(inBand.map((v) => [v.id, v.deps.filter((d) => inBand.some((x) => x.id === d))]));
  if (findCycle(graph)) return { waves: [], outOfBand, chain: [], chainPoints: 0, views };

  // Layer = longest dependency depth. Within a layer, split into waves so that every wave is pairwise disjoint, in priority order.
  const depth = new Map<string, number>();
  const depthOf = (id: string): number => {
    if (depth.has(id)) return depth.get(id)!;
    const d = Math.max(0, ...(graph.get(id) ?? []).map((x) => depthOf(x) + 1));
    depth.set(id, d);
    return d;
  };
  inBand.forEach((v) => depthOf(v.id));
  const byId = new Map(inBand.map((v) => [v.id, v]));
  const disjoint = (a: EpicView, b: EpicView) => !a.paths.some((p) => b.paths.some((q) => overlaps(p, q))) && !a.patchable.some((p) => b.patchable.some((q) => patchOverlap(p, q)));
  const waves: EpicView[][] = [];
  const maxDepth = Math.max(-1, ...depth.values());
  for (let d = 0; d <= maxDepth; d++) {
    const layer = inBand.filter((v) => depth.get(v.id) === d);
    const pending = [...layer];
    while (pending.length) {
      const wave: EpicView[] = [];
      for (const v of [...pending]) {
        if (wave.every((w) => disjoint(w, v))) { wave.push(v); pending.splice(pending.indexOf(v), 1); }
      }
      waves.push(wave);
    }
  }
  // Longest chain by points.
  const best = new Map<string, { points: number; path: string[] }>();
  const chainOf = (id: string): { points: number; path: string[] } => {
    if (best.has(id)) return best.get(id)!;
    const v = byId.get(id)!;
    const sub = (graph.get(id) ?? []).map(chainOf).sort((a, b) => b.points - a.points)[0];
    const r = { points: v.points + (sub?.points ?? 0), path: [...(sub?.path ?? []), id] };
    best.set(id, r);
    return r;
  };
  const top = inBand.map((v) => chainOf(v.id)).sort((a, b) => b.points - a.points)[0];
  return { waves, outOfBand, chain: top?.path ?? [], chainPoints: top?.points ?? 0, views };
}

export function renderCriticalPath(m: Model): string {
  const { waves, outOfBand, chain, chainPoints, views } = planActive(m);
  const conc = m.constitution?.data?.concurrency ?? {};
  const inBandPoints = views.filter((v) => v.kind !== "out_of_band").reduce((a, v) => a + v.points, 0);
  const oobPoints = outOfBand.reduce((a, v) => a + v.points, 0);
  const width = Math.max(0, ...waves.map((w) => w.length));
  const L: string[] = [];
  L.push("# Critical path", "", "Generated by `constitution-tooling render` from `tasks/epics/`. Do not edit by hand; change the epic files and render again.", "");
  L.push("## Totals", "");
  L.push(`| Active epics | Open points | Out-of-band epics | Out-of-band points | Waves | Widest wave | Longest chain (points) |`);
  L.push(`| :--- | :--- | :--- | :--- | :--- | :--- | :--- |`);
  L.push(`| ${views.length - outOfBand.length} | ${inBandPoints} | ${outOfBand.length} | ${oobPoints} | ${waves.length} | ${width} | ${chainPoints} |`, "");
  L.push("## Longest chain", "");
  L.push(chain.length ? chain.map((id) => `EPIC-${id}`).join(" → ") + ` (${chainPoints} points). This bounds wall-clock time however many lanes run.` : "No active in-band epics.", "");
  L.push("## Waves", "", "An epic joins a wave when every dependency sits in an earlier wave and it is scope-disjoint from every other epic in the wave. A wave of one is a serial segment.", "");
  L.push("| Wave | Epic | Kind | Open points | Owns | May patch | Depends on |", "| :--- | :--- | :--- | :--- | :--- | :--- | :--- |");
  waves.forEach((w, i) => w.forEach((v) => L.push(`| ${i + 1} | EPIC-${v.id} ${v.name} | ${v.kind} | ${v.points} | ${v.paths.map((p) => `\`${p}\``).join(", ") || "—"} | ${v.patchable.map((p) => `\`${p}\``).join(", ") || "—"} | ${v.deps.map((d) => `EPIC-${d}`).join(", ") || "—"} |`)));
  if (!waves.length) L.push("| — | — | — | — | — | — | — |");
  L.push("");
  if (outOfBand.length) {
    L.push("## Out of band", "", "Epics planned from issues. They run whenever the user chooses, outside the dependency graph, and must stay scope-disjoint from whatever wave is running.", "");
    L.push("| Epic | Source | Open points | Owns | Conflicts with |", "| :--- | :--- | :--- | :--- | :--- |");
    for (const v of outOfBand) {
      const conflicts = views.filter((x) => x.id !== v.id && x.kind !== "out_of_band" && (x.paths.some((p) => v.paths.some((q) => overlaps(p, q))) || x.patchable.some((p) => v.patchable.some((q) => patchOverlap(p, q))))).map((x) => `EPIC-${x.id}`);
      L.push(`| EPIC-${v.id} ${v.name} | ${v.doc.data.source ?? "—"} | ${v.points} | ${v.paths.map((p) => `\`${p}\``).join(", ") || "—"} | ${conflicts.join(", ") || "none"} |`);
    }
    L.push("");
  }
  L.push("## Build order", "", "```mermaid", "flowchart LR");
  for (const v of views) L.push(`  ${v.id}["EPIC-${v.id} ${v.name} (${v.points})"]`);
  for (const v of views) for (const d of v.deps) L.push(`  ${d} --> ${v.id}`);
  L.push("```", "", "An arrow points from a prerequisite to the epic that depends on it, so it reads in the order work flows, the same direction as the longest chain above.", "");
  L.push("## Ticket order inside each epic", "", "A dependency-respecting listing, not a chain: `needs` names a ticket's own `depends_on` inside its epic, and a ticket without one has no in-epic dependency. Readiness is epic-level: a ticket finished on an unmerged branch satisfies no other epic's dependency until the containing PR merges.", "");
  for (const v of views) {
    const tickets: any[] = v.doc.data.tickets ?? [];
    const g = new Map(tickets.map((t) => [t.id, t.depends_on ?? []]));
    const order: string[] = []; const seen = new Set<string>();
    const visit = (id: string) => { if (seen.has(id)) return; seen.add(id); for (const d of g.get(id) ?? []) visit(d); order.push(id); };
    tickets.forEach((t) => visit(t.id));
    L.push(`- **EPIC-${v.id}:** ${order.map((id) => { const t = tickets.find((x) => x.id === id); const notes = [t?.status && t.status !== "planned" ? t.status : "", (g.get(id) ?? []).length ? `needs ${(g.get(id) ?? []).join(", ")}` : ""].filter(Boolean); return `${id}${notes.length ? ` (${notes.join("; ")})` : ""}`; }).join(", ")}`);
  }
  if (!views.length) L.push("- none");
  L.push("");
  L.push("## Concurrency mechanics", "");
  L.push(`- **Worktree:** ${conc.worktree ?? "one worktree per epic, not recorded yet in constitution.yaml"}`);
  L.push(`- **Branch naming:** ${conc.branch ?? "type/description, not recorded yet in constitution.yaml"}`);
  L.push(`- **Merge strategy:** ${conc.merge ?? "not recorded yet in constitution.yaml"}`);
  L.push("");
  return L.join("\n");
}
